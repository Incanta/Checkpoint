// Vendors the Unreal Angelscript TextMate grammar from Hazelight's
// vscode-unreal-angelscript extension (MIT) and adds static highlighting rules
// for things the extension colors with its language server instead.
//
// The extension colors type names (actors, components, structs) with semantic
// tokens from a live Unreal Editor connection. We have no editor connection,
// so we add the prefix rules from the extension's own snippet grammar
// (angelscript_snippet.tmLanguage.json). Unreal enforces those prefixes, so
// they cover nearly every type.
//
// The app and desktop can't share a package (app must not depend on common),
// so the result is written to both places. A test checks they stay identical.
//
// Usage:
//   node scripts/syntax/vendor-angelscript-grammar.mjs <path-to-vscode-unreal-angelscript>

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUTPUTS = [
  "src/app/src/lib/syntax/angelscript.tmLanguage.json",
  "src/clients/desktop/src/renderer/syntax/angelscript.tmLanguage.json",
];

const upstreamRoot = process.argv[2];
if (!upstreamRoot) {
  console.error("Usage: node scripts/syntax/vendor-angelscript-grammar.mjs <path-to-vscode-unreal-angelscript>");
  process.exit(1);
}

const upstreamFile = path.join(upstreamRoot, "extension/syntaxes/angelscript.tmLanguage.json");
const grammar = JSON.parse(fs.readFileSync(upstreamFile, "utf-8"));

let upstreamCommit = "unknown";
try {
  upstreamCommit = execFileSync("git", ["-C", upstreamRoot, "log", "-1", "--format=%h", "--", "extension/syntaxes/angelscript.tmLanguage.json"], { encoding: "utf-8" }).trim();
} catch {
  // Not a git checkout; keep "unknown".
}

const IDENT = "[A-Za-z_][A-Za-z0-9_]*";
// Prefix + capital, and at least one lowercase letter so ALL_CAPS constants
// and macros (UPROPERTY, EXIT_CODE) are not treated as types.
const prefixed = (prefix) => `\\b${prefix}[A-Z](?=[A-Za-z0-9_]*[a-z])[A-Za-z0-9_]*\\b`;

const additions = [
  // n"Name" literals: color the n prefix, then a normal string.
  {
    begin: '\\b(n)(")',
    beginCaptures: {
      1: { name: "storage.type.string.name.angelscript" },
      2: { name: "punctuation.definition.string.begin.angelscript" },
    },
    end: '"',
    endCaptures: { 0: { name: "punctuation.definition.string.end.angelscript" } },
    name: "string.quoted.double.name.angelscript",
    patterns: [{ include: "#string_escaped_char" }, { include: "#line_continuation_character" }],
  },
  // Parameter modifiers: int&in, FVector&out, T&inout.
  { match: "(?<=&)(in|out|inout)\\b", name: "keyword.type.angelscript" },
  // Type names by Unreal prefix. Order matters on ties: the first listed wins.
  { match: "\\bU[A-Za-z0-9_]*Component\\b", name: "support.type.component.angelscript" },
  { match: prefixed("A"), name: "support.type.actor.angelscript" },
  { match: prefixed("F"), name: "support.type.struct.angelscript" },
  { match: prefixed("E"), name: "support.type.enum.angelscript" },
  { match: prefixed("[UT]"), name: "support.type.angelscript" },
  // Namespaces and enum scopes: Math::Abs, System::GetGameTimeInSeconds.
  // Type-prefixed names before :: already matched above.
  { match: `\\b(${IDENT})(?=\\s*::)`, name: "entity.name.namespace.angelscript" },
  // Function calls and declarations. Keywords like if/while are listed earlier
  // in the grammar, so they win at the same position.
  { match: `\\b(${IDENT})(?=\\s*\\()`, name: "entity.name.function.angelscript" },
];

// Insert after the upstream keyword/macro/string rules and before the generic
// comment/number/operator/string includes, so upstream rules win ties.
const firstInclude = grammar.patterns.findIndex((p) => p.include);
grammar.patterns.splice(firstInclude === -1 ? grammar.patterns.length : firstInclude, 0, ...additions);

const out = {
  information_for_contributors: [
    "Generated by scripts/syntax/vendor-angelscript-grammar.mjs. Do not edit by hand; edit the script and rerun it.",
    `Based on extension/syntaxes/angelscript.tmLanguage.json from vscode-unreal-angelscript (commit ${upstreamCommit}).`,
    "Copyright 2019 Hazelight Games AB, MIT License: https://github.com/Hazelight/vscode-unreal-angelscript/blob/master/LICENSE",
  ],
  displayName: "Angelscript",
  ...grammar,
  name: "angelscript",
};

const text = JSON.stringify(out, null, 2) + "\n";
for (const rel of OUTPUTS) {
  const dest = path.join(repoRoot, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, text);
  console.log(`Wrote ${rel}`);
}
